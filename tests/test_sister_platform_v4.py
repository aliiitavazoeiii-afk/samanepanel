"""Bundle definitions, per-size pricing and exact physical inventory deductions."""
import tempfile
import unittest
from pathlib import Path
from daily_sales_service.engine import init_db,ImportErrorDetail
from daily_sales_service.master_v2_logic import add_model,batch_adjust,sku_rows
from daily_sales_service.platform_catalog import book_sale,create_listing,sale_summary
from daily_sales_service.platform_packs_v4 import (
    available_models,define_bundle,list_bundle_variants,list_bundle_groups,
    save_variant_prices,book_bundle_sale
)
from daily_sales_service.effective_costs import today,schedule_cost

CATEGORY="شورت زنانه دارما"

class BundleV4Test(unittest.TestCase):
    def setUp(self):
        temp=tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.conn=init_db(Path(temp.name)/"test.sqlite3")
        self.addCleanup(self.conn.close)
        add_model(self.conn,CATEGORY,"مدل چاپی","","مشکی، سفید، سرمه‌ای","M، L")
        self.key=available_models(self.conn,CATEGORY)[0]["key"]

    def sku(self,color,size):
        return next(x for x in sku_rows(self.conn,CATEGORY) if x["color"]==color and x["size"]==size)

    def set_stock(self,color,size,qty):
        sku=self.sku(color,size)
        batch_adjust(self.conn,CATEGORY,sku["id"],size,"home",{sku["id"]:qty},"شمارش دوره‌ای")

    def make(self,channel="basalam",sizes=("M","L"),colors=("مشکی","سفید","مشکی")):
        return define_bundle(self.conn,channel,CATEGORY,self.key,len(colors),list(colors),list(sizes),"پک ترکیبی دارما")

    def test_define_three_color_slots_two_sizes_and_price_each_size(self):
        self.make()
        models=list_bundle_groups(self.conn,"basalam")
        self.assertEqual(len(models),1)
        self.assertEqual(models[0]["pack_qty"],3)
        self.assertEqual(models[0]["colors"],["مشکی","سفید","مشکی"])
        rows=list_bundle_variants(self.conn,"basalam")
        self.assertEqual({v["size"] for v in rows},{"M","L"})
        self.assertTrue(all(v["price_toman"] is None for v in rows))
        variants={row["size"]:row["variant_id"] for row in rows}
        save_variant_prices(self.conn,"basalam",{variants["M"]:400000,variants["L"]:425000})
        new=list_bundle_variants(self.conn,"basalam")
        self.assertEqual({r["size"]:r["price_toman"] for r in new},{"M":400000,"L":425000})
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM platform_bundle_parts").fetchone()[0],6)
        # No generic SKU sale-price price is generated by platform-specific pricing.
        self.assertIsNone(self.conn.execute("SELECT price_toman FROM master_channel_prices LIMIT 1").fetchone())

    def test_sale_deducts_duplicate_color_slots_exactly_and_preserves_other_size(self):
        result=self.make()
        variant={v["size"]:v["variant_id"] for v in list_bundle_variants(self.conn,"basalam")}
        save_variant_prices(self.conn,"basalam",{variant["M"]:480000})
        for color in ("مشکی","سفید","سرمه‌ای"):
            for size in ("M","L"):self.set_stock(color,size,10)
        schedule_cost(self.conn,CATEGORY,"","*",65000,today())
        sold=book_bundle_sale(self.conn,"basalam",variant["M"],2,"home",today(),"BAS-101")
        self.assertEqual(sold["units"],6)
        self.assertEqual(sold["gross"],960000)
        self.assertEqual(sold["cogs"],6*65000)
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("مشکی","M")["id"],)).fetchone()[0],6)
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("سفید","M")["id"],)).fetchone()[0],8)
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("سرمه‌ای","M")["id"],)).fetchone()[0],10)
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("مشکی","L")["id"],)).fetchone()[0],10)
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM platform_bundle_sale_parts").fetchone()[0],2)
        with self.assertRaises(ImportErrorDetail):
            book_bundle_sale(self.conn,"basalam",variant["M"],2,"home",today(),"BAS-101")
        self.assertEqual(sale_summary(self.conn)["basalam"]["units"],6)

    def test_insufficient_one_color_rolls_back_everything(self):
        self.make(sizes=("M",))
        v=list_bundle_variants(self.conn,"basalam")[0]["variant_id"]
        save_variant_prices(self.conn,"basalam",{v:400000})
        self.set_stock("مشکی","M",20)
        self.set_stock("سفید","M",1)
        with self.assertRaises(ImportErrorDetail):
            book_bundle_sale(self.conn,"basalam",v,2,"home",today(),"BAS-FAIL")
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM platform_bundle_sales").fetchone()[0],0)
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("مشکی","M")["id"],)).fetchone()[0],20)

    def test_missing_color_size_rejects_whole_listing_without_partial_rows(self):
        add_model(self.conn,CATEGORY,"مدل نصفه","","مشکی","M")
        add_model(self.conn,CATEGORY,"مدل نصفه","","سفید","L")
        key=next(m["key"] for m in available_models(self.conn,CATEGORY) if m["title"]=="مدل نصفه")
        with self.assertRaises(ImportErrorDetail):
            define_bundle(self.conn,"site",CATEGORY,key,2,["مشکی","سفید"],["M","L"])
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM platform_bundle_models").fetchone()[0],0)

    def test_six_slots_and_mold_small_medium_large(self):
        colors=["مشکی","سفید","سرمه‌ای"]*2
        self.make(channel="site",sizes=("M",),colors=colors)
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM platform_bundle_parts").fetchone()[0],6)
        add_model(self.conn,"قالب","قالب طبی","","قهوه‌ای","کوچک، متوسط، بزرگ")
        mold=available_models(self.conn,"قالب")[0]
        define_bundle(self.conn,"mold","قالب",mold["key"],1,["قهوه‌ای"],["کوچک","متوسط","بزرگ"])
        self.assertEqual(len(list_bundle_variants(self.conn,"mold")),3)

    def test_prices_platform_specific_legacy_preserved(self):
        self.make(channel="basalam",sizes=("M",))
        self.make(channel="site",sizes=("M",))
        salam=list_bundle_variants(self.conn,"basalam")[0]["variant_id"]
        site=list_bundle_variants(self.conn,"site")[0]["variant_id"]
        save_variant_prices(self.conn,"basalam",{salam:310000})
        save_variant_prices(self.conn,"site",{site:350000})
        self.assertEqual(list_bundle_variants(self.conn,"site")[0]["price_toman"],350000)
        self.assertEqual(list_bundle_variants(self.conn,"basalam")[0]["price_toman"],310000)
        with self.assertRaises(ImportErrorDetail):
            save_variant_prices(self.conn,"site",{salam:999999})
        self.assertEqual(list_bundle_variants(self.conn,"basalam")[0]["price_toman"],310000)

    def test_unpriced_bundle_fails_closed_and_duplicate_order_legacy(self):
        self.make(sizes=("M",),colors=("مشکی",))
        v=list_bundle_variants(self.conn,"basalam")[0]["variant_id"]
        self.set_stock("مشکی","M",5)
        with self.assertRaises(ImportErrorDetail):
            book_bundle_sale(self.conn,"basalam",v,1,"home",today(),"abc")
        save_variant_prices(self.conn,"basalam",{v:200000})
        # Original V3 record/order remains valid and blocks cross-schema duplicate.
        from daily_sales_service.master_v2_logic import set_channel_prices
        set_channel_prices(self.conn,"basalam",CATEGORY,"","M",50000)
        old=create_listing(self.conn,"basalam",self.sku("مشکی","M")["id"],"تکی قدیمی",1)
        book_sale(self.conn,"basalam",old,1,"home",today(),"same-ref")
        with self.assertRaises(ImportErrorDetail):
            book_bundle_sale(self.conn,"basalam",v,1,"home",today(),"same-ref")
        self.assertEqual(self.conn.execute("SELECT seller_stock FROM master_products WHERE id=?",(self.sku("مشکی","M")["id"],)).fetchone()[0],4)

    def test_new_ui_is_model_then_pack_colors_and_checkbox_sizes(self):
        from daily_sales_service.platform_packs_ui import definition_page,price_page,daily_sales_page
        page=definition_page(self.conn,"basalam",CATEGORY).body.decode()
        self.assertIn("مدل محصول",page)
        self.assertIn("تعداد در هر بسته",page)
        self.assertIn("عدد 6",page)
        self.assertIn('type="checkbox" name="size"',page)
        self.assertIn("رنگ هر عدد",page)
        self.assertIn("جستجو",page)
        empty=price_page(self.conn,"basalam").body.decode()
        self.assertIn("هنوز محصولی",empty)
        self.make()
        page=price_page(self.conn,"basalam").body.decode()
        self.assertIn("سایز M",page)
        self.assertIn("سایز L",page)
        self.assertIn("قیمت فروش کل بسته",page)
        self.assertIn("پک ترکیبی دارما",daily_sales_page(self.conn,"basalam").body.decode())

if __name__=="__main__":unittest.main()
